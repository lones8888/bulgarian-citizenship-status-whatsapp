let aktif = "en";

export function dilAyarla(dil) {
  aktif = dil === "tr" ? "tr" : "en";
  return aktif;
}

export const aktifDil = () => aktif;
export const yerel = () => (aktif === "tr" ? "tr-TR" : "en-GB");

export function t(anahtar, degisken) {
  const metin = METIN[aktif][anahtar] ?? METIN.en[anahtar] ?? anahtar;
  return degisken ? metin.replace(/\{(\w+)\}/gu, (tam, ad) => (ad in degisken ? String(degisken[ad]) : tam)) : metin;
}

/** data-i18n (yazi), data-i18n-html (ayni metindeki <strong>), -placeholder, -aria; data-i18n-n = {n} degiskeni. */
export function sayfayiCevir(kok = document) {
  document.documentElement.lang = aktif;
  for (const el of kok.querySelectorAll("[data-i18n]")) {
    el.textContent = t(el.dataset.i18n, el.dataset.i18nN ? { n: el.dataset.i18nN } : undefined);
  }
  for (const el of kok.querySelectorAll("[data-i18n-html]")) el.innerHTML = t(el.dataset.i18nHtml);
  for (const el of kok.querySelectorAll("[data-i18n-placeholder]")) el.placeholder = t(el.dataset.i18nPlaceholder);
  for (const el of kok.querySelectorAll("[data-i18n-aria]")) el.setAttribute("aria-label", t(el.dataset.i18nAria));
}

